import { z } from 'zod';
import {
  CLAUDE_ANSWER,
  CLAUDE_CONTROL,
  CLAUDE_CONTROLLED,
  CLAUDE_CONTROLLER,
  CLAUDE_CONTROLLER_REGISTRATION,
  CLAUDE_LINK,
  CLAUDE_PROMPT,
  CLAUDE_PROMPT_ID,
  CLAUDE_SESSION,
  CLAUDE_SESSION_ID,
  CLAUDE_SESSION_STATE,
  CLAUDE_START,
  CLAUDE_STARTED,
  CLAUDE_STATUS,
  CLAUDE_THREAD_CURSOR,
  CLAUDE_THREAD_LIMIT,
  CLAUDE_THREAD_PAGE,
  CLAUDE_SESSION_LIST_MAX,
  CLAUDE_USAGE,
} from '../claude';
import { NO_BODY, endpoint } from './endpoint';
import { NOTHING, QUERY_FLAG, queryLimit } from './primitives';

const SESSION_PARAMS = z.strictObject({ sessionId: CLAUDE_SESSION_ID });

const PROMPT_PARAMS = z.strictObject({ promptId: CLAUDE_PROMPT_ID });

export const CLAUDE_ENDPOINTS = {
  readClaudeStatus: endpoint({
    method: 'GET',
    path: '/api/claude/status',
    access: 'owner',
    summary:
      'Read retained legacy history availability, attached CLI integration and sampled usage; Desktop runtime control is retired',
    params: NOTHING,
    query: NOTHING,
    body: NO_BODY,
    response: CLAUDE_STATUS,
  }),
  listClaudeSessions: endpoint({
    method: 'GET',
    path: '/api/claude/sessions',
    access: 'owner',
    summary:
      'List retained legacy session metadata and current CLI live files, including stable IDs, titles, folders and archive flags; sessions owned by SmartEverything app chats are not listed',
    params: NOTHING,
    query: z.strictObject({
      state: CLAUDE_SESSION_STATE.optional(),
      archived: QUERY_FLAG.default(false),
      limit: queryLimit(100, CLAUDE_SESSION_LIST_MAX),
    }),
    body: NO_BODY,
    response: z.array(CLAUDE_SESSION),
  }),
  readClaudeSession: endpoint({
    method: 'GET',
    path: '/api/claude/sessions/:sessionId',
    access: 'owner',
    summary: 'Read one legacy session and its explicit read-only native-control capabilities',
    params: SESSION_PARAMS,
    query: NOTHING,
    body: NO_BODY,
    response: CLAUDE_SESSION,
  }),
  listClaudeThread: endpoint({
    method: 'GET',
    path: '/api/claude/sessions/:sessionId/thread',
    access: 'owner',
    summary: 'Read retained legacy transcript messages with stable latest and older-page cursors',
    params: SESSION_PARAMS,
    query: z.strictObject({
      before: CLAUDE_THREAD_CURSOR.optional(),
      limit: queryLimit(50, CLAUDE_THREAD_LIMIT),
    }),
    body: NO_BODY,
    response: CLAUDE_THREAD_PAGE,
  }),
  readClaudeUsage: endpoint({
    method: 'GET',
    path: '/api/claude/usage',
    access: 'owner',
    summary:
      'Read previously sampled legacy plan usage or newer attached CLI usage without starting inference',
    params: NOTHING,
    query: NOTHING,
    body: NO_BODY,
    response: CLAUDE_USAGE,
  }),
  listClaudePrompts: endpoint({
    method: 'GET',
    path: '/api/claude/prompts',
    access: 'owner',
    summary:
      'Permission requests, questions and plan approvals that Claude sessions are waiting on, oldest first',
    params: NOTHING,
    query: z.strictObject({ sessionId: CLAUDE_SESSION_ID.optional() }),
    body: NO_BODY,
    response: z.array(CLAUDE_PROMPT),
  }),
  controlClaudeSession: endpoint({
    method: 'POST',
    path: '/api/claude/sessions/:sessionId/control',
    access: 'owner',
    summary: 'Retired compatibility operation; use controlClaudeCliSession on the owned CLI chat',
    params: SESSION_PARAMS,
    query: NOTHING,
    body: CLAUDE_CONTROL,
    response: CLAUDE_CONTROLLED,
  }),
  startClaudeSession: endpoint({
    method: 'POST',
    path: '/api/claude/sessions',
    access: 'owner',
    summary:
      'Retired compatibility operation; use startClaudeCliSession to create an owned actual CLI chat',
    params: NOTHING,
    query: NOTHING,
    body: CLAUDE_START,
    response: CLAUDE_STARTED,
  }),
  installClaudeLink: endpoint({
    method: 'POST',
    path: '/api/claude/link',
    access: 'owner',
    summary:
      'Explicitly install or repair the attached Claude Code link for approvals, scoped home tools and direct native tool access',
    params: NOTHING,
    query: NOTHING,
    body: NO_BODY,
    response: CLAUDE_LINK,
  }),
  removeClaudeLink: endpoint({
    method: 'DELETE',
    path: '/api/claude/link',
    access: 'owner',
    summary: 'Remove the attached Claude Code link and revoke its integration credential',
    params: NOTHING,
    query: NOTHING,
    body: NO_BODY,
    response: CLAUDE_LINK,
  }),
  registerClaudeController: endpoint({
    method: 'POST',
    path: '/api/claude/controller',
    access: 'owner',
    summary: 'Retired Desktop controller registration; use owned CLI chats or attached CLI tools',
    params: NOTHING,
    query: NOTHING,
    body: NO_BODY,
    response: CLAUDE_CONTROLLER_REGISTRATION,
  }),
  removeClaudeController: endpoint({
    method: 'DELETE',
    path: '/api/claude/controller',
    access: 'owner',
    summary: 'Retired Desktop controller management; existing historical files remain untouched',
    params: NOTHING,
    query: NOTHING,
    body: NO_BODY,
    response: CLAUDE_CONTROLLER,
  }),
  answerClaudePrompt: endpoint({
    method: 'POST',
    path: '/api/claude/prompts/:promptId/answer',
    access: 'owner',
    summary:
      'Answer a waiting Claude prompt: allow or deny a permission request or plan, or pick the answers to its questions',
    params: PROMPT_PARAMS,
    query: NOTHING,
    body: CLAUDE_ANSWER,
    response: CLAUDE_PROMPT,
  }),
} as const;
