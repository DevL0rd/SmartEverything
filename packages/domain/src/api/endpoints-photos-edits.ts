import {
  EDIT_JOB,
  EDIT_JOB_PARAMS,
  EDIT_JOB_STARTED,
  PHOTO_EDIT,
  PHOTO_EDIT_PATCH,
  PHOTO_EDIT_PATCH_PARAMS,
  PHOTO_EDIT_BASE,
  PHOTO_EDIT_SAVE,
  PHOTO_EDIT_SAVED,
  PHOTO_ERASE,
  PHOTO_ERASED,
  VIDEO_EDIT,
} from '../photos/edits';
import { NO_BODY, endpoint } from './endpoint';
import { DRIVE_ITEM_PARAMS } from './endpoints-drive';
import { NOTHING } from './primitives';

export const PHOTOS_EDIT_ENDPOINTS = {
  readPhotoEdit: endpoint({
    method: 'GET',
    path: '/api/drive/photos/items/:itemId/edit',
    access: 'member',
    summary: 'The last edit of a photo and whether it can be saved over the original',
    params: DRIVE_ITEM_PARAMS,
    query: NOTHING,
    body: NO_BODY,
    response: PHOTO_EDIT,
  }),
  readPhotoEditBase: endpoint({
    method: 'GET',
    path: '/api/drive/photos/items/:itemId/edit/base',
    access: 'member',
    summary:
      'The preview of the original a photo is edited from, the version kept before its first edit or the file itself when it was never edited',
    params: DRIVE_ITEM_PARAMS,
    query: NOTHING,
    body: NO_BODY,
    response: PHOTO_EDIT_BASE,
  }),
  readPhotoEditPatch: endpoint({
    method: 'GET',
    path: '/api/drive/photos/items/:itemId/edit/patches/:patchId',
    access: 'member',
    summary: 'The erased area image kept in the last edit of a photo',
    params: PHOTO_EDIT_PATCH_PARAMS,
    query: NOTHING,
    body: NO_BODY,
    response: PHOTO_EDIT_PATCH,
  }),
  savePhotoEdit: endpoint({
    method: 'POST',
    path: '/api/drive/photos/items/:itemId/edit',
    access: 'member',
    summary: 'Save an edited photo as a new version of the photo or as a copy',
    params: DRIVE_ITEM_PARAMS,
    query: NOTHING,
    body: PHOTO_EDIT_SAVE,
    response: PHOTO_EDIT_SAVED,
  }),
  revertPhotoEdit: endpoint({
    method: 'POST',
    path: '/api/drive/photos/items/:itemId/revert',
    access: 'member',
    summary: 'Restore the original photo from before it was edited',
    params: DRIVE_ITEM_PARAMS,
    query: NOTHING,
    body: NO_BODY,
    response: PHOTO_EDIT_SAVED,
  }),
  erasePhotoArea: endpoint({
    method: 'POST',
    path: '/api/drive/photos/items/:itemId/erase',
    access: 'member',
    summary:
      'Erase the brushed area of a photo and answer a patch, with its picture, to preview and keep in the edit',
    params: DRIVE_ITEM_PARAMS,
    query: NOTHING,
    body: PHOTO_ERASE,
    response: PHOTO_ERASED,
  }),
  editPhotoVideo: endpoint({
    method: 'POST',
    path: '/api/drive/photos/items/:itemId/video',
    access: 'member',
    summary: 'Trim or stabilize a video in the background and save it as a new version or a copy',
    params: DRIVE_ITEM_PARAMS,
    query: NOTHING,
    body: VIDEO_EDIT,
    response: EDIT_JOB_STARTED,
  }),
  readPhotoEditJob: endpoint({
    method: 'GET',
    path: '/api/drive/photos/edit-jobs/:jobId',
    access: 'member',
    summary: 'How far a video edit has got and the item it saved',
    params: EDIT_JOB_PARAMS,
    query: NOTHING,
    body: NO_BODY,
    response: EDIT_JOB,
  }),
} as const;
