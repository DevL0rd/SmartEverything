import { z } from 'zod';
import { LIBRARY_BUCKET, LIBRARY_PAGE, LIBRARY_PAGE_QUERY, LIBRARY_SCOPE } from '../photos/library';
import {
  LOCKED_PIN_SET,
  LOCKED_STATE,
  LOCKED_UNLOCK,
  LOCKED_UNLOCKED,
  PHOTO_ARCHIVED,
  PHOTO_DESCRIPTION_SET,
  PHOTO_ITEMS_CHANGED,
  PHOTO_ITEM_IDS,
  PHOTO_META_PATCH,
} from '../photos/organise';
import { NO_BODY, endpoint } from './endpoint';
import { DRIVE_ITEM_LINK, DRIVE_ITEM_PARAMS } from './endpoints-drive';
import { DONE, NOTHING } from './primitives';

const MONTH_PARAMS = z.strictObject({ month: z.string().regex(/^\d{4}-(0[1-9]|1[0-2])$/) });

export const PHOTOS_ORGANISE_ENDPOINTS = {
  editPhotoMeta: endpoint({
    method: 'PATCH',
    path: '/api/drive/photos/items/meta',
    access: 'member',
    summary: 'Change the date or location of photos, or shift their dates by an offset',
    params: NOTHING,
    query: NOTHING,
    body: PHOTO_META_PATCH,
    response: PHOTO_ITEMS_CHANGED,
  }),
  setPhotoDescription: endpoint({
    method: 'PUT',
    path: '/api/drive/photos/items/:itemId/description',
    access: 'member',
    summary: 'Write or clear the description of a photo; the file itself stays untouched',
    params: DRIVE_ITEM_PARAMS,
    query: NOTHING,
    body: PHOTO_DESCRIPTION_SET,
    response: PHOTO_ITEMS_CHANGED,
  }),
  archivePhotos: endpoint({
    method: 'POST',
    path: '/api/drive/photos/archive',
    access: 'member',
    summary: 'Hide photos from the library and map without deleting them',
    params: NOTHING,
    query: NOTHING,
    body: PHOTO_ITEM_IDS,
    response: PHOTO_ITEMS_CHANGED,
  }),
  unarchivePhotos: endpoint({
    method: 'POST',
    path: '/api/drive/photos/unarchive',
    access: 'member',
    summary: 'Bring archived photos back to the library',
    params: NOTHING,
    query: NOTHING,
    body: PHOTO_ITEM_IDS,
    response: PHOTO_ITEMS_CHANGED,
  }),
  readPhotoArchived: endpoint({
    method: 'GET',
    path: '/api/drive/photos/items/:itemId/archived',
    access: 'member',
    summary: 'Whether the caller archived this photo',
    params: DRIVE_ITEM_PARAMS,
    query: NOTHING,
    body: NO_BODY,
    response: PHOTO_ARCHIVED,
  }),
  readArchiveBuckets: endpoint({
    method: 'GET',
    path: '/api/drive/photos/archive',
    access: 'member',
    summary: 'The months of archived photos with how many each holds',
    params: NOTHING,
    query: LIBRARY_SCOPE,
    body: NO_BODY,
    response: z.array(LIBRARY_BUCKET),
  }),
  readArchivePage: endpoint({
    method: 'GET',
    path: '/api/drive/photos/archive/:month',
    access: 'member',
    summary: 'One month of archived photos as library columns',
    params: MONTH_PARAMS,
    query: LIBRARY_PAGE_QUERY,
    body: NO_BODY,
    response: LIBRARY_PAGE,
  }),
  readLockedState: endpoint({
    method: 'GET',
    path: '/api/drive/photos/locked-state',
    access: 'member',
    summary: 'Whether the caller has set a Locked folder PIN',
    params: NOTHING,
    query: NOTHING,
    body: NO_BODY,
    response: LOCKED_STATE,
  }),
  setLockedPin: endpoint({
    method: 'PUT',
    path: '/api/drive/photos/locked/pin',
    access: 'member',
    summary: 'Set the Locked folder PIN, or change it with the current one',
    params: NOTHING,
    query: NOTHING,
    body: LOCKED_PIN_SET,
    response: DONE,
  }),
  unlockLockedFolder: endpoint({
    method: 'POST',
    path: '/api/drive/photos/locked/unlock',
    access: 'member',
    summary: 'Open the Locked folder with the PIN and answer a short-lived token for this client',
    params: NOTHING,
    query: NOTHING,
    body: LOCKED_UNLOCK,
    response: LOCKED_UNLOCKED,
  }),
  lockLockedFolder: endpoint({
    method: 'POST',
    path: '/api/drive/photos/locked/lock',
    access: 'member',
    summary: 'Close the Locked folder and end the token sent in the x-photos-locked-token header',
    params: NOTHING,
    query: NOTHING,
    body: NO_BODY,
    response: DONE,
  }),
  readLockedBuckets: endpoint({
    method: 'GET',
    path: '/api/drive/photos/locked',
    access: 'member',
    summary:
      'The months of the Locked folder; needs the unlock token in the x-photos-locked-token header',
    params: NOTHING,
    query: LIBRARY_SCOPE,
    body: NO_BODY,
    response: z.array(LIBRARY_BUCKET),
  }),
  readLockedPage: endpoint({
    method: 'GET',
    path: '/api/drive/photos/locked/:month',
    access: 'member',
    summary:
      'One month of the Locked folder as library columns; needs the unlock token in the x-photos-locked-token header',
    params: MONTH_PARAMS,
    query: LIBRARY_PAGE_QUERY,
    body: NO_BODY,
    response: LIBRARY_PAGE,
  }),
  readLockedLinks: endpoint({
    method: 'POST',
    path: '/api/drive/photos/locked/links',
    access: 'member',
    summary:
      'Short-lived links to photos in the Locked folder that end when it locks; needs the unlock token in the x-photos-locked-token header',
    params: NOTHING,
    query: NOTHING,
    body: PHOTO_ITEM_IDS,
    response: z.array(DRIVE_ITEM_LINK),
  }),
  moveIntoLockedFolder: endpoint({
    method: 'POST',
    path: '/api/drive/photos/locked/move-in',
    access: 'member',
    summary: 'Move photos into the Locked folder, out of every other place',
    params: NOTHING,
    query: NOTHING,
    body: PHOTO_ITEM_IDS,
    response: PHOTO_ITEMS_CHANGED,
  }),
  moveOutOfLockedFolder: endpoint({
    method: 'POST',
    path: '/api/drive/photos/locked/move-out',
    access: 'member',
    summary:
      'Move photos back to the library; needs the unlock token in the x-photos-locked-token header',
    params: NOTHING,
    query: NOTHING,
    body: PHOTO_ITEM_IDS,
    response: PHOTO_ITEMS_CHANGED,
  }),
  deleteFromLockedFolder: endpoint({
    method: 'POST',
    path: '/api/drive/photos/locked/delete',
    access: 'member',
    summary:
      'Delete photos in the Locked folder for good, never through the drive trash; needs the unlock token in the x-photos-locked-token header',
    params: NOTHING,
    query: NOTHING,
    body: PHOTO_ITEM_IDS,
    response: PHOTO_ITEMS_CHANGED,
  }),
} as const;
