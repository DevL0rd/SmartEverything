import { z } from 'zod';
import {
  CLAUDE_ANSWER,
  CLAUDE_OPERATION,
  CLAUDE_OPERATION_ACCEPTED,
  CLAUDE_CONTROL,
  CLAUDE_CONTROLLED,
  CLAUDE_CONTROLLER,
  CLAUDE_CONTROLLER_REGISTRATION,
  CLAUDE_LINK,
  CLAUDE_PROMPT,
  CLAUDE_PROMPT_ID,
  CLAUDE_SESSION,
  CLAUDE_SESSION_ID,
  CLAUDE_SESSION_STATE,
  CLAUDE_START,
  CLAUDE_STARTED,
  CLAUDE_STATUS,
  CLAUDE_THREAD_CURSOR,
  CLAUDE_THREAD_PAGE,
  CLAUDE_USAGE,
} from '../claude';
import {
  COMPUTER_NATIVE_MCP_POLICY,
  COMPUTER_AI_MODEL,
  COMPUTER_AI_NATIVE_TOOL,
  COMPUTER_AI_SETTINGS_PATCH,
  COMPUTER_AI_STATUS,
} from '../computer-ai';
import { COMPUTER_AI_RUNTIME } from '../computer-ai-runtime';
import { JSON_VALUE } from '../values';
import { PROVIDER_METADATA } from '../node/provider-controls';
import { NO_BODY, endpoint } from './endpoint';
import { NOTHING, QUERY_FLAG, queryLimit } from './primitives';

const COMPUTER = z.strictObject({ deviceId: z.uuid() });
const SESSION = COMPUTER.extend({ sessionId: CLAUDE_SESSION_ID });
const PROMPT = COMPUTER.extend({ promptId: CLAUDE_PROMPT_ID });
const OPERATION_ID = { operation_id: z.uuid().optional() };
const [firstControl, ...remainingControls] = CLAUDE_CONTROL.options;
const CONTROL_WITH_OPERATION = z.discriminatedUnion('action', [
  firstControl.extend(OPERATION_ID),
  ...remainingControls.map((schema) => schema.extend(OPERATION_ID)),
]);

export const COMPUTER_AI_ENDPOINTS = {
  readComputerNativeMcpPolicy: endpoint({
    method: 'GET',
    path: '/api/computers/:deviceId/ai/:runtime/mcp-policy',
    access: 'owner',
    summary: 'Read independent outbound home-tool access for this computer and native runtime',
    params: COMPUTER.extend({ runtime: COMPUTER_AI_RUNTIME }),
    query: NOTHING,
    body: NO_BODY,
    response: COMPUTER_NATIVE_MCP_POLICY,
  }),
  updateComputerNativeMcpPolicy: endpoint({
    method: 'PUT',
    path: '/api/computers/:deviceId/ai/:runtime/mcp-policy',
    access: 'owner',
    summary:
      'Set outbound native MCP enablement and exact tool areas independently of execution and legacy access',
    params: COMPUTER.extend({ runtime: COMPUTER_AI_RUNTIME }),
    query: NOTHING,
    body: COMPUTER_NATIVE_MCP_POLICY,
    response: COMPUTER_NATIVE_MCP_POLICY,
  }),
  readComputerClaudeOperation: endpoint({
    method: 'GET',
    path: '/api/computers/:deviceId/claude/operations/:operationId',
    access: 'owner',
    summary: 'Read a correlated native operation receipt without resubmitting the action',
    params: COMPUTER.extend({ operationId: z.uuid() }),
    query: NOTHING,
    body: NO_BODY,
    response: CLAUDE_OPERATION,
  }),
  readComputerAi: endpoint({
    method: 'GET',
    path: '/api/computers/:deviceId/claude',
    access: 'member',
    summary:
      'Read independent Claude control and subscription-provider settings and capabilities of one computer',
    params: COMPUTER,
    query: NOTHING,
    body: NO_BODY,
    response: COMPUTER_AI_STATUS,
  }),
  updateComputerAi: endpoint({
    method: 'PATCH',
    path: '/api/computers/:deviceId/claude',
    access: 'owner',
    summary:
      'Configure independent Claude native control and subscription provider on one computer',
    params: COMPUTER,
    query: NOTHING,
    body: COMPUTER_AI_SETTINGS_PATCH,
    response: COMPUTER_AI_STATUS,
  }),
  readComputerClaudeStatus: endpoint({
    method: 'GET',
    path: '/api/computers/:deviceId/claude/status',
    access: 'owner',
    summary: 'Read actual Claude native status on the selected computer',
    params: COMPUTER,
    query: NOTHING,
    body: NO_BODY,
    response: CLAUDE_STATUS,
  }),
  readComputerClaudeProviderMetadata: endpoint({
    method: 'GET',
    path: '/api/computers/:deviceId/claude/provider-metadata',
    access: 'owner',
    summary:
      'Read exact subscription-provider settings schemas and available operations on one computer',
    params: COMPUTER,
    query: NOTHING,
    body: NO_BODY,
    response: PROVIDER_METADATA,
  }),
  listComputerClaudeModels: endpoint({
    method: 'GET',
    path: '/api/computers/:deviceId/claude/models',
    access: 'owner',
    summary: 'Discover subscription models supplied by the selected computer',
    params: COMPUTER,
    query: NOTHING,
    body: NO_BODY,
    response: z.array(COMPUTER_AI_MODEL),
  }),
  listComputerClaudeSessions: endpoint({
    method: 'GET',
    path: '/api/computers/:deviceId/claude/sessions',
    access: 'owner',
    summary:
      'List legacy history and current attached CLI sessions on the selected computer; sessions owned by SmartEverything app chats are not listed',
    params: COMPUTER,
    query: z.strictObject({
      state: CLAUDE_SESSION_STATE.optional(),
      archived: QUERY_FLAG.default(false),
      limit: queryLimit(100, 200),
    }),
    body: NO_BODY,
    response: z.array(CLAUDE_SESSION),
  }),
  readComputerClaudeSession: endpoint({
    method: 'GET',
    path: '/api/computers/:deviceId/claude/sessions/:sessionId',
    access: 'owner',
    summary: 'Read one actual native Claude session on the selected computer',
    params: SESSION,
    query: NOTHING,
    body: NO_BODY,
    response: CLAUDE_SESSION,
  }),
  listComputerClaudeThread: endpoint({
    method: 'GET',
    path: '/api/computers/:deviceId/claude/sessions/:sessionId/thread',
    access: 'owner',
    summary: 'Read actual native session messages on the selected computer',
    params: SESSION,
    query: z.strictObject({ before: CLAUDE_THREAD_CURSOR.optional(), limit: queryLimit(50, 200) }),
    body: NO_BODY,
    response: CLAUDE_THREAD_PAGE,
  }),
  readComputerClaudeUsage: endpoint({
    method: 'GET',
    path: '/api/computers/:deviceId/claude/usage',
    access: 'owner',
    summary: 'Read native Claude plan usage last sampled on the selected computer',
    params: COMPUTER,
    query: NOTHING,
    body: NO_BODY,
    response: CLAUDE_USAGE,
  }),
  listComputerClaudePrompts: endpoint({
    method: 'GET',
    path: '/api/computers/:deviceId/claude/prompts',
    access: 'owner',
    summary: 'List actual native permissions, plans and questions on the selected computer',
    params: COMPUTER,
    query: z.strictObject({ sessionId: CLAUDE_SESSION_ID.optional() }),
    body: NO_BODY,
    response: z.array(CLAUDE_PROMPT),
  }),
  controlComputerClaudeSession: endpoint({
    method: 'POST',
    path: '/api/computers/:deviceId/claude/sessions/:sessionId/control',
    access: 'owner',
    summary:
      'Retired compatibility operation; use controlClaudeCliSession on the exact owned CLI chat',
    params: SESSION,
    query: NOTHING,
    body: CONTROL_WITH_OPERATION,
    response: z.union([CLAUDE_CONTROLLED, CLAUDE_OPERATION_ACCEPTED]),
  }),
  startComputerClaudeSession: endpoint({
    method: 'POST',
    path: '/api/computers/:deviceId/claude/sessions',
    access: 'owner',
    summary:
      'Retired compatibility operation; use startClaudeCliSession for an owned actual CLI chat',
    params: COMPUTER,
    query: NOTHING,
    body: CLAUDE_START.extend(OPERATION_ID),
    response: z.union([CLAUDE_STARTED, CLAUDE_OPERATION_ACCEPTED]),
  }),
  installComputerClaudeLink: endpoint({
    method: 'POST',
    path: '/api/computers/:deviceId/claude/link',
    access: 'owner',
    summary: 'Install or repair the native Claude link on the selected computer',
    params: COMPUTER,
    query: NOTHING,
    body: NO_BODY,
    response: CLAUDE_LINK,
  }),
  removeComputerClaudeLink: endpoint({
    method: 'DELETE',
    path: '/api/computers/:deviceId/claude/link',
    access: 'owner',
    summary: 'Remove and revoke the native Claude link on the selected computer',
    params: COMPUTER,
    query: NOTHING,
    body: NO_BODY,
    response: CLAUDE_LINK,
  }),
  registerComputerClaudeController: endpoint({
    method: 'POST',
    path: '/api/computers/:deviceId/claude/controller',
    access: 'owner',
    summary:
      'Retired Desktop controller registration on a computer; use owned CLI chats or attached CLI tools',
    params: COMPUTER,
    query: NOTHING,
    body: NO_BODY,
    response: CLAUDE_CONTROLLER_REGISTRATION,
  }),
  removeComputerClaudeController: endpoint({
    method: 'DELETE',
    path: '/api/computers/:deviceId/claude/controller',
    access: 'owner',
    summary:
      'Retired Desktop controller management on a computer; existing historical files remain untouched',
    params: COMPUTER,
    query: NOTHING,
    body: NO_BODY,
    response: CLAUDE_CONTROLLER,
  }),
  answerComputerClaudePrompt: endpoint({
    method: 'POST',
    path: '/api/computers/:deviceId/claude/prompts/:promptId/answer',
    access: 'owner',
    summary: 'Answer an actual native Claude prompt on the selected computer',
    params: PROMPT,
    query: NOTHING,
    body: CLAUDE_ANSWER,
    response: CLAUDE_PROMPT,
  }),
  listComputerClaudeTools: endpoint({
    method: 'GET',
    path: '/api/computers/:deviceId/claude/tools',
    access: 'owner',
    summary:
      'Discover native harness tools and exact available argument schemas on the selected computer',
    params: COMPUTER,
    query: z.strictObject({ sessionId: CLAUDE_SESSION_ID.optional() }),
    body: NO_BODY,
    response: z.array(COMPUTER_AI_NATIVE_TOOL),
  }),
  callComputerClaudeTool: endpoint({
    method: 'POST',
    path: '/api/computers/:deviceId/claude/sessions/:sessionId/tools',
    access: 'owner',
    summary:
      'Invoke a discovered native harness tool with validated exact arguments on the selected computer',
    params: SESSION,
    query: NOTHING,
    body: z.strictObject({
      ...OPERATION_ID,
      name: z.string().min(1).max(200),
      arguments: z.record(z.string(), JSON_VALUE),
    }),
    response: JSON_VALUE,
  }),
} as const;
