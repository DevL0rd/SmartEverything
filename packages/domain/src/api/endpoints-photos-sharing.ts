import { z } from 'zod';
import {
  ALBUM_ACTIVITY,
  ALBUM_ACTIVITY_CREATE,
  ALBUM_ACTIVITY_PARAMS,
  ALBUM_MEMBER,
  ALBUM_MEMBERS_SET,
  ALBUM_MEMBER_PARAMS,
  ALBUM_PARAMS,
  PARTNER_AUTO_SAVE,
  PARTNER_PARAMS,
  PARTNER_SAVE,
  PARTNER_SAVED,
  PARTNER_SET,
  PARTNER_SHARE,
  PHOTO_SHARING,
} from '../photos/sharing';
import { NO_BODY, endpoint } from './endpoint';
import { CURSOR_QUERY, pageOf } from './endpoints-drive';
import { DONE, NOTHING } from './primitives';

export const PHOTOS_SHARING_ENDPOINTS = {
  readPhotoSharing: endpoint({
    method: 'GET',
    path: '/api/drive/photos/sharing',
    access: 'member',
    summary: 'Shared albums, partner sharing and the latest activity for the Sharing page',
    params: NOTHING,
    query: NOTHING,
    body: NO_BODY,
    response: PHOTO_SHARING,
  }),
  setPhotoAlbumMembers: endpoint({
    method: 'PUT',
    path: '/api/drive/photos/albums/:albumId/members',
    access: 'member',
    summary: 'Add people to an album or change whether they can add photos',
    params: ALBUM_PARAMS,
    query: NOTHING,
    body: ALBUM_MEMBERS_SET,
    response: z.array(ALBUM_MEMBER).readonly(),
  }),
  removePhotoAlbumMember: endpoint({
    method: 'DELETE',
    path: '/api/drive/photos/albums/:albumId/members/:profileId',
    access: 'member',
    summary: 'Remove a person from an album; the photos they added leave it',
    params: ALBUM_MEMBER_PARAMS,
    query: NOTHING,
    body: NO_BODY,
    response: DONE,
  }),
  joinPhotoAlbum: endpoint({
    method: 'POST',
    path: '/api/drive/photos/albums/:albumId/join',
    access: 'member',
    summary: 'Accept an invitation to a shared album',
    params: ALBUM_PARAMS,
    query: NOTHING,
    body: NO_BODY,
    response: ALBUM_MEMBER,
  }),
  leavePhotoAlbum: endpoint({
    method: 'POST',
    path: '/api/drive/photos/albums/:albumId/leave',
    access: 'member',
    summary: 'Leave a shared album; the photos the caller added leave it',
    params: ALBUM_PARAMS,
    query: NOTHING,
    body: NO_BODY,
    response: DONE,
  }),
  listPhotoAlbumActivity: endpoint({
    method: 'GET',
    path: '/api/drive/photos/albums/:albumId/activity',
    access: 'member',
    summary: 'Photos added, comments, likes and joins in a shared album, newest first',
    params: ALBUM_PARAMS,
    query: CURSOR_QUERY,
    body: NO_BODY,
    response: pageOf(ALBUM_ACTIVITY),
  }),
  addPhotoAlbumActivity: endpoint({
    method: 'POST',
    path: '/api/drive/photos/albums/:albumId/activity',
    access: 'member',
    summary: 'Comment on a shared album or one of its photos, or like it',
    params: ALBUM_PARAMS,
    query: NOTHING,
    body: ALBUM_ACTIVITY_CREATE,
    response: ALBUM_ACTIVITY,
  }),
  removePhotoAlbumActivity: endpoint({
    method: 'DELETE',
    path: '/api/drive/photos/albums/:albumId/activity/:activityId',
    access: 'member',
    summary: 'Delete the caller’s own comment or like',
    params: ALBUM_ACTIVITY_PARAMS,
    query: NOTHING,
    body: NO_BODY,
    response: DONE,
  }),
  setPhotoPartner: endpoint({
    method: 'PUT',
    path: '/api/drive/photos/partner',
    access: 'member',
    summary:
      'Offer a partner all photos, or the photos of chosen people, from a start day, or change an offer',
    params: NOTHING,
    query: NOTHING,
    body: PARTNER_SET,
    response: PARTNER_SHARE,
  }),
  acceptPhotoPartner: endpoint({
    method: 'POST',
    path: '/api/drive/photos/partner/:shareId/accept',
    access: 'member',
    summary: 'Accept a partner’s offer so their photos appear in a tab of the library',
    params: PARTNER_PARAMS,
    query: NOTHING,
    body: NO_BODY,
    response: PARTNER_SHARE,
  }),
  stopPhotoPartner: endpoint({
    method: 'POST',
    path: '/api/drive/photos/partner/:shareId/stop',
    access: 'member',
    summary: 'Stop sharing with a partner or stop receiving their photos',
    params: PARTNER_PARAMS,
    query: NOTHING,
    body: NO_BODY,
    response: PARTNER_SHARE,
  }),
  savePartnerPhotos: endpoint({
    method: 'POST',
    path: '/api/drive/photos/partner/:shareId/save',
    access: 'member',
    summary: 'Save chosen photos of a partner into the caller’s own library',
    params: PARTNER_PARAMS,
    query: NOTHING,
    body: PARTNER_SAVE,
    response: PARTNER_SAVED,
  }),
  setPartnerAutoSave: endpoint({
    method: 'PUT',
    path: '/api/drive/photos/partner/:shareId/auto-save',
    access: 'member',
    summary: 'Save every new photo of a partner into the caller’s library automatically, or stop',
    params: PARTNER_PARAMS,
    query: NOTHING,
    body: PARTNER_AUTO_SAVE,
    response: PARTNER_SHARE,
  }),
} as const;
