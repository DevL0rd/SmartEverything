describe('node registry assembly', () => {
  it('uses each id once across every category', () => {
    const ids = ALL_NODE_KINDS.map((kind) => kind.id);
    expect(new Set(ids).size).toBe(ids.length);
  });

  it('passes every define rule', () => {
    expect(registryProblems(ALL_NODE_KINDS)).toEqual([]);
    for (const kind of ALL_NODE_KINDS) expect(kindProblems(kind)).toEqual([]);
  });

  it('ships every registered kind, the listed v1 kinds among them', () => {
    const shipped = NODE_REGISTRY.shipped().map((kind) => kind.id);
    expect([...shipped].sort()).toEqual(NODE_REGISTRY.kinds.map((kind) => kind.id).sort());
    expect(shipped).toEqual(expect.arrayContaining([...V1_IDS]));
    expect(ALL_NODE_KINDS.filter((kind) => kind.tier === 'v1')).toHaveLength(V1_IDS.length);
  });

  it('ships no kind outside the shipped tiers', () => {
    for (const kind of NODE_REGISTRY.shipped()) expect(SHIPPED_TIERS).toContain(kind.tier);
    expect(NODE_REGISTRY.shipped().some((kind) => kind.tier === 'v1.1')).toBe(true);
    expect(NODE_REGISTRY.shipped().some((kind) => kind.id === 'debug.breakpoint')).toBe(true);
  });
});
