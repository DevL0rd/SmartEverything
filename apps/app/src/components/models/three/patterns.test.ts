import { MODEL_SPEC_PATTERNS } from '@smarteverything/domain';
import { NoColorSpace, RepeatWrapping, SRGBColorSpace } from 'three';
import { describe, expect, it } from 'vitest';
import { MODEL_LOD_LEVELS } from './geometry';
import {
  PATTERN_STYLES,
  patternPixels,
  patternSize,
  patternTexture,
  patternValue,
  valueNoise,
} from './patterns';

function levels(data: Uint8Array): readonly number[] {
  return Array.from({ length: data.length / 4 }, (_, at) => data[at * 4] ?? -1);
}

describe('procedural patterns', () => {
  it('have a style for every spec pattern token', () => {
    expect(Object.keys(PATTERN_STYLES).sort()).toEqual([...MODEL_SPEC_PATTERNS].sort());
  });

  it('are generated by code with no texture at tile LOD', () => {
    expect(MODEL_LOD_LEVELS.map(patternSize)).toEqual([0, 128, 256]);
  });

  it.each(MODEL_SPEC_PATTERNS)('%s is deterministic, opaque grey and not flat', (pattern) => {
    const first = patternPixels(pattern, 32);
    const again = patternPixels(pattern, 32);
    expect(first.data).toEqual(again.data);
    expect(first.data.length).toBe(32 * 32 * 4);
    for (let at = 0; at < first.data.length; at += 4) {
      expect(first.data[at + 1]).toBe(first.data[at]);
      expect(first.data[at + 3]).toBe(255);
    }
    expect(new Set(levels(first.data)).size).toBeGreaterThan(1);
  });

  it.each(MODEL_SPEC_PATTERNS)('%s keeps its contrast low', (pattern) => {
    const style = PATTERN_STYLES[pattern];
    const values = levels(patternPixels(pattern, 32).data);
    const spread = (Math.max(...values) - Math.min(...values)) / 255;
    expect(spread).toBeLessThanOrEqual(style.contrast + 0.01);
    if (style.use === 'tone') expect(Math.max(...values)).toBeGreaterThan(240);
  });

  it.each(MODEL_SPEC_PATTERNS)('%s tiles seamlessly across its edges', (pattern) => {
    for (const t of [0.1, 0.37, 0.8]) {
      expect(patternValue(pattern, 0, t)).toBeCloseTo(patternValue(pattern, 1, t), 5);
      expect(patternValue(pattern, t, 0)).toBeCloseTo(patternValue(pattern, t, 1), 5);
    }
  });

  it('value noise stays in range and wraps on its period', () => {
    for (let step = 0; step < 20; step += 1) {
      const u = step / 20;
      const value = valueNoise(u, 1 - u, 8, 1);
      expect(value).toBeGreaterThanOrEqual(0);
      expect(value).toBeLessThanOrEqual(1);
      expect(valueNoise(u + 1, 1 - u, 8, 1)).toBeCloseTo(value, 9);
    }
  });

  it('tone textures are sRGB colour maps, relief textures are linear, both repeat', () => {
    const wood = patternTexture(patternPixels('wood-grain', 16));
    const knit = patternTexture(patternPixels('knit', 16));
    expect(wood.colorSpace).toBe(SRGBColorSpace);
    expect(knit.colorSpace).toBe(NoColorSpace);
    expect(knit.wrapS).toBe(RepeatWrapping);
    expect(knit.repeat.x).toBe(PATTERN_STYLES.knit.repeat);
    expect(knit.image.width).toBe(16);
    wood.dispose();
    knit.dispose();
  });
});
