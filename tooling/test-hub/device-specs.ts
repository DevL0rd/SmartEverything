import type { JsonValue } from '@smarteverything/domain';
import type { Behaviour, DeviceSpec } from './devices.ts';

const on = (perDay = 4, start = 6, end = 23): Behaviour => ({ kind: 'toggle', perDay, start, end });
const series = (base: number, swing: number, noise: number): Behaviour => ({
  kind: 'series',
  base,
  swing,
  noise,
});
const fixed = (value: JsonValue): Behaviour => ({ kind: 'fixed', value });

const light = (id: string, name: string, room: string, color = false): DeviceSpec => ({
  id,
  kind: 'light',
  name,
  room,
  model: color ? 'Test colour bulb' : 'Test white bulb',
  manufacturer: 'Synthetic',
  capabilities: [
    { key: 'power', access: 'read_write', behaviour: on(5, 6, 23) },
    { key: 'brightness', access: 'read_write', behaviour: fixed(70) },
    { key: 'color_temperature', access: 'read_write', behaviour: fixed(3200) },
    ...(color
      ? [
          {
            key: 'color',
            access: 'read_write' as const,
            behaviour: fixed({ hue: 30, saturation: 40, value: 90 }),
          },
        ]
      : []),
  ],
});

const plug = (id: string, name: string, room: string, watts: number): DeviceSpec => ({
  id,
  kind: 'plug',
  name,
  room,
  model: 'Test smart plug',
  manufacturer: 'Synthetic',
  capabilities: [
    { key: 'power', access: 'read_write', behaviour: on(3, 7, 22) },
    { key: 'power_draw', access: 'read', behaviour: series(watts, watts * 0.2, watts * 0.05) },
    { key: 'energy', access: 'read', behaviour: fixed(12.5) },
  ],
});

const sensor = (id: string, name: string, room: string, air = false): DeviceSpec => ({
  id,
  kind: 'sensor',
  name,
  room,
  model: air ? 'Test air sensor' : 'Test climate sensor',
  manufacturer: 'Synthetic',
  capabilities: [
    { key: 'temperature', access: 'read', behaviour: series(21.5, 2.5, 0.3) },
    { key: 'humidity', access: 'read', behaviour: series(48, 8, 1.5) },
    ...(air
      ? [
          { key: 'co2', access: 'read' as const, behaviour: series(650, 250, 30) },
          { key: 'pm25', access: 'read' as const, behaviour: series(9, 5, 2) },
        ]
      : []),
    { key: 'battery', access: 'read', behaviour: fixed(86) },
  ],
});

const contact = (id: string, name: string, room: string): DeviceSpec => ({
  id,
  kind: 'sensor',
  name,
  room,
  model: 'Test contact sensor',
  manufacturer: 'Synthetic',
  capabilities: [
    { key: 'contact', access: 'read', behaviour: on(6, 6, 23) },
    { key: 'battery', access: 'read', behaviour: fixed(92) },
  ],
});

