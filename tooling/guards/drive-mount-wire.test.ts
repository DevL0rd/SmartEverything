import { readFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';
import { GO_OUTPUT, GOLDEN_DIRECTORY, renderDriveMountWire } from '../generate-drive-mount-wire';

const COMMAND = 'node --import tsx tooling/generate-drive-mount-wire.ts';

describe('drive mount wire generation', () => {
  const generated = renderDriveMountWire();

  it(`keeps the generated Go constants current (run ${COMMAND})`, () => {
    expect(readFileSync(GO_OUTPUT, 'utf8')).toBe(generated.go);
  });

  it('marks the generated Go file as generated', () => {
    expect(
      generated.go.startsWith(
        '// Code generated by tooling/generate-drive-mount-wire.ts; DO NOT EDIT.',
      ),
    ).toBe(true);
  });

  it(`keeps exactly the generated golden frames on disk (run ${COMMAND})`, () => {
    const files = readdirSync(GOLDEN_DIRECTORY)
      .filter((file) => file.endsWith('.bin'))
      .sort();
    expect(files).toEqual([...generated.golden.keys()].sort());
    for (const [file, bytes] of generated.golden) {
      expect(
        Buffer.compare(readFileSync(join(GOLDEN_DIRECTORY, file)), Buffer.from(bytes)),
        file,
      ).toBe(0);
    }
  });

  it('generates one Go constant per op, error code and meta key', () => {
    for (const name of [
      'OpHello',
      'OpLookup',
      'OpFsync',
      'PushChanged',
      'PushLockLost',
      'ErrENOENT',
      'ErrENETUNREACH',
      'KeyOpKey',
      'KeyNames',
    ]) {
      expect(generated.go, name).toMatch(new RegExp(`\\t${name}\\s`));
    }
  });
});
