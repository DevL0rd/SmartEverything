  FRAME_TYPES,
  HEADER_BYTES,
  INODE_TYPES,
  LEASE_MS,
  LOCK_TYPES,
  MAX_FRAME_BYTES,
  MAX_META_BYTES,
  MAX_PAYLOAD_BYTES,
  META_KEYS,
  MOUNT_SUBPROTOCOL,
  NAME_MAX_BYTES,
